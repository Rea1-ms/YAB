'use strict';

// Regeneration only: use the existing Electron SVG renderer, with no new
// build dependency or runtime SVG library. Normal builds use saved PNGs.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

if (!process.versions.electron) {
  const { spawnSync } = require('child_process');
  const env = { ...process.env };
  delete env.ELECTRON_RUN_AS_NODE;
  const result = spawnSync(require('electron'), [__filename], { env, windowsHide: true, stdio: 'inherit' });
  if (result.error) throw result.error;
  process.exitCode = result.status ?? 1;
} else {
  const { app, BrowserWindow } = require('electron');
  app.whenReady().then(async () => {
    const root = path.join(__dirname, 'assets/checkbox');
    const sizes = [16, 20, 24, 28, 32, 40, 48, 56, 64];
    const states = ['unchecked', 'checked', 'indeterminate'];
    const sha256 = data => crypto.createHash('sha256').update(data).digest('hex');
    const manifest = {
      repository: 'https://github.com/microsoft/fluentui-system-icons',
      revision: 'e15fc0de25fab983e3e42bac8798be69a85c23bf',
      license: 'MIT', sizes, states, sources: {}, resources: [],
    };
    const window = new BrowserWindow({ show: false, webPreferences: {
      sandbox: true, contextIsolation: true, nodeIntegration: false,
    } });
    await window.loadURL('data:text/html,<meta charset="utf-8"><title>Local checkbox asset generation</title>');
    for (const [stateIndex, state] of states.entries()) {
      const svg = fs.readFileSync(path.join(root, 'source', `${state}.svg`));
      manifest.sources[`${state}.svg`] = sha256(svg);
      const images = await window.webContents.executeJavaScript(`(async () => {
        const image = new Image();
        image.src = ${JSON.stringify(`data:image/svg+xml;base64,${svg.toString('base64')}`)};
        await image.decode();
        return ${JSON.stringify(sizes)}.map(size => {
          const canvas = document.createElement('canvas');
          canvas.width = canvas.height = size;
          const context = canvas.getContext('2d');
          context.drawImage(image, 0, 0, size, size);
          // Keep the upstream alpha silhouette; tint at runtime for each theme
          // and native control state instead of storing duplicate color sets.
          const mask = context.getImageData(0, 0, size, size);
          for (let i = 0; i < mask.data.length; i += 4) {
            mask.data[i] = mask.data[i + 1] = mask.data[i + 2] = 0;
          }
          context.putImageData(mask, 0, 0);
          return canvas.toDataURL('image/png').split(',')[1];
        });
      })()`);
      for (const [sizeIndex, size] of sizes.entries()) {
        const file = `${state}-${size}.png`;
        const png = Buffer.from(images[sizeIndex], 'base64');
        fs.writeFileSync(path.join(root, file), png);
        manifest.resources.push({ id: 2000 + stateIndex * sizes.length + sizeIndex, file, sha256: sha256(png) });
      }
    }
    const header = '// Generated by generate_checkbox_assets.cjs; do not edit.\n#pragma once\n'
      + `static constexpr int checkboxSizes[] = {${sizes.join(', ')}};\n`
      + `static constexpr int checkboxSizeCount = ${sizes.length};\n`
      + 'static constexpr int checkboxResourceIds[3][checkboxSizeCount] = {\n'
      + states.map((_, index) => `    {${manifest.resources.slice(index * sizes.length, (index + 1) * sizes.length).map(resource => resource.id).join(', ')}}`).join(',\n')
      + '\n};\n';
    fs.writeFileSync(path.join(__dirname, 'native/checkbox-assets.h'), header);
    manifest.headerSha256 = sha256(header);
    fs.writeFileSync(path.join(root, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
    window.destroy();
    console.log(`Saved ${manifest.resources.length} checkbox masks (100%–400%).`);
    app.quit();
  }).catch(error => { console.error(error); app.exit(1); });
}
